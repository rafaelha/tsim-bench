"""Collect papers/*/k_max.json into SUMMARY.md (per-paper overview and per-circuit table).

Usage: uv run python tools/summary.py
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).parent.parent
PAPERS = ROOT / "papers"


def k_cell(r, key):
    if r.get(f"{key}_k") is not None:
        return r[f"{key}_k"]
    error = r.get(f"{key}_error", "")
    overflow = re.search(r"active width would reach (\d+)", error)
    if overflow:
        return f"≥{overflow.group(1)}*"
    limit = re.search(r"needs (\d+) active qubits", error)
    return f"{limit.group(1)}†" if limit else "error"


def numeric(values):
    return [v for v in values if isinstance(v, int)]


def title(folder):
    readme = folder / "README.md"
    first = readme.read_text().splitlines()[0] if readme.exists() else folder.name
    return first.lstrip("# ").strip()


def main():
    rows, overview = [], []
    for folder in sorted(PAPERS.iterdir()):
        path = folder / "k_max.json"
        if not path.exists():
            continue
        results = json.loads(path.read_text())
        arxiv = folder.name.split("_")[0]
        tsim = [k_cell(r, "tsim") for r in results]
        clifft = [k_cell(r, "clifft") for r in results]
        extra_c = sorted({c for c in clifft if isinstance(c, str)})
        extra_t = sorted({t for t in tsim if isinstance(t, str)})
        overview.append(
            f"| [{arxiv}](papers/{folder.name}) | {title(folder)} | {len(results)} | "
            f"{min(numeric(tsim))}–{max(numeric(tsim))}{' (+ ' + ', '.join(extra_t) + ')' if extra_t else ''} | "
            f"{min(numeric(clifft))}–{max(numeric(clifft))}{' (+ ' + ', '.join(extra_c) + ')' if extra_c else ''} |"
        )
        for r, t, c in zip(results, tsim, clifft):
            gates = ", ".join(f"{n} {g}" for g, n in r["non_clifford_gates"].items()) or "none"
            rows.append(f"| {arxiv} | `{pathlib.Path(r['file']).name}` | {gates} | {t} | {c} | "
                        f"{k_cell(r, 'clifft_noschedule')} |")
    text = [
        "# Active width k_max of published non-Clifford circuits",
        "",
        "Generated by `tools/summary.py` from `papers/*/k_max.json`.",
        "Tsim: main@883d787, default `active_statevector` strategy (largest statevector component width).",
        "Clifft 0.12.0: `default_hir_pass_manager()` + `ActiveWidthSchedulePass()` (`peak_active_width`); the last",
        "column is Clifft without the scheduler. `≥60*`: Clifft's planner would exceed its dense-state limit.",
        "`63†`: Tsim's active_statevector strategy would need that many active qubits (limit 30) and refuses.",
        "Gate counts treat each `REPEAT` body once.",
        "",
        "## Per paper",
        "",
        "| arXiv | paper | circuits | Tsim k | Clifft k |",
        "|---|---|---|---|---|",
        *overview,
        "",
        "## Per circuit",
        "",
        "| arXiv | circuit | non-Clifford gates | Tsim k | Clifft k (scheduler) | Clifft k (default) |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
    ]
    (ROOT / "SUMMARY.md").write_text("\n".join(text))
    print(f"wrote SUMMARY.md: {len(overview)} papers, {len(rows)} circuits")


if __name__ == "__main__":
    main()
