r"""Rebuild every figure from ``repro/results`` and compile ``repro/report/report.pdf``.

    uv run python -m repro.make_report            # all studies, whatever has been sampled so far
    uv run python -m repro.make_report --no-pdf   # figures and report.tex only
    uv run python -m repro.make_report --only soft_d5

Works on partial results: points that are not sampled yet are simply missing from the plots, and a
study whose figure code fails is reported in the PDF instead of aborting the build. The LaTeX is
compiled with the first engine found on PATH (``tectonic``, ``latexmk``, ``pdflatex``; override with
``REPRO_LATEX``).
"""

import argparse
import re
import datetime
import json
import os
import shutil
import subprocess
import traceback

from repro import common


def esc(s):
    return (s.replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
            .replace("#", "\\#"))


def study_section(name):
    mod = common.study_module(name)
    results = common.load_results(name)
    meta = mod.META
    parts = [f"\\section{{{esc(meta['paper'])}}}\\label{{sec:{name}}}",
             f"\\noindent\\textbf{{arXiv:{meta['arxiv']}}} \\quad Study module \\texttt{{repro/studies/{esc(name)}.py}}\n"]
    doc = (mod.__doc__ or "").strip().split("\n\n")
    if len(doc) > 1:
        parts.append(tex_paragraphs("\n\n".join(doc[1:])))
    try:
        figs = mod.figures(results)
    except Exception:  # noqa: BLE001
        tb = traceback.format_exc()
        print(tb)
        parts.append("\\begin{verbatim}\nfigure code failed:\n" + tb[-1500:] + "\n\\end{verbatim}")
        figs = []
    for f in figs:
        rel = os.path.relpath(f.path, common.REPORT)
        if f.kind == "table":
            parts.append("\\begin{table}[H]\n\\centering\\small\n"
                         f"\\caption*{{\\textbf{{{f.title}}}\\\\ {f.caption}\\\\ \\textit{{Compute: {esc(f.budget)}}}}}\n"
                         f"\\resizebox{{\\linewidth}}{{!}}{{\\input{{{rel}}}}}\n\\end{{table}}")
        else:
            parts.append("\\begin{figure}[H]\n\\centering\n"
                         f"\\includegraphics[width=\\linewidth]{{{rel}}}\n"
                         f"\\caption*{{\\textbf{{{f.title}}}\\\\ \\textit{{Compute: {esc(f.budget)}}}\\\\ {f.caption}}}\n"
                         "\\end{figure}")
    parts.append("\\clearpage")
    tot = summarize(results)
    return "\n\n".join(parts), tot


def tex_paragraphs(text):
    """Docstring text -> LaTeX: keep ``$...$`` math, escape the rest, turn ``- `` lists into itemize."""
    out = []
    for para in text.split("\n\n"):
        lines = [l.strip() for l in para.splitlines()]
        if lines and lines[0].startswith("- "):
            items, cur = [], []
            for l in lines:
                if l.startswith("- "):
                    if cur:
                        items.append(" ".join(cur))
                    cur = [l[2:]]
                else:
                    cur.append(l)
            items.append(" ".join(cur))
            out.append("\\begin{itemize}\\setlength\\itemsep{0pt}\n" + "\n".join("\\item " + inline(i) for i in items) + "\n\\end{itemize}")
        else:
            out.append(inline(" ".join(lines)))
    return "\n\n".join(out)


def inline(s):
    segs = s.split("$")
    for i in range(0, len(segs), 2):
        segs[i] = re.sub(r"``(.*?)``", r"\\texttt{\1}", esc(segs[i]))
    return "$".join(segs)


def summarize(results):
    t = dict(seconds=0.0, compile=0.0, shots=0, points=len(results))
    for r in results.values():
        t["seconds"] += r["totals"]["seconds"]
        t["compile"] += r["totals"]["compile_seconds"]
        t["shots"] += r["totals"]["shots"]
    return t


def preamble(total_rows, builds):
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    return rf"""\documentclass[10pt]{{article}}
\usepackage[margin=2.2cm]{{geometry}}
\usepackage{{amsmath,graphicx,booktabs,caption,float,longtable}}
\usepackage[hidelinks]{{hyperref}}
\captionsetup{{font=small,labelformat=empty}}
\title{{Decoder-free reproductions of magic-state simulations\\with real non-Clifford gates on a GPU}}
\author{{Generated by \texttt{{repro/make\_report.py}}}}
\date{{{now}}}
\begin{{document}}
\maketitle

\noindent Every figure below is regenerated from scratch by \texttt{{uv run python -m repro.run\_all}}:
circuits come from the authors' generators, are sampled with the Tsim CUDA statevector executor
(postselection on the device), and every point records its own GPU time, compile time, shot count,
GPU model and Tsim build. Where the paper simulated a Clifford proxy ($S$ in place of $T$, or a
$|Y\rangle$ / $|{{+i}}\rangle$ state), the same proxy is sampled again on the GPU and plotted next to
the published numbers, as a check of the GPU kernel; the real non-Clifford circuit ($T$ gates,
rotations) is sampled alongside. Logical error rates are per kept shot; bands and error bars span
hypotheses within a factor 1000 of the maximum likelihood (the convention of \texttt{{sinter}}).
Triangles mark upper bounds for points with zero observed errors.

\smallskip\noindent Tsim builds: {esc(builds)}.

\begin{{table}}[h]\centering\small
\begin{{tabular}}{{l r r r}}
\toprule
study & points & GPU sampling & shots \\
\midrule
{total_rows}
\bottomrule
\end{{tabular}}
\end{{table}}
\tableofcontents
\clearpage
"""


def compile_pdf(tex):
    engine = os.environ.get("REPRO_LATEX")
    candidates = [engine] if engine else ["tectonic", "latexmk", "pdflatex"]
    for e in candidates:
        exe = shutil.which(e) or next((p for p in (os.path.expanduser(f"~/.local/bin/{e}"), os.path.expanduser(f"~/opt/{e}/{e}"))
                                       if os.path.exists(p)), None)
        if not exe:
            continue
        if "tectonic" in e:
            cmd = [exe, "--keep-logs", tex.name]
        elif "latexmk" in e:
            cmd = [exe, "-pdf", "-interaction=nonstopmode", tex.name]
        else:
            cmd = [exe, "-interaction=nonstopmode", tex.name]
        runs = 1 if ("tectonic" in e or "latexmk" in e) else 2
        for _ in range(runs):
            p = subprocess.run(cmd, cwd=tex.parent, capture_output=True, text=True)
        print(f"{e}: exit {p.returncode}" + ("" if p.returncode == 0 else "\n" + (p.stdout + p.stderr)[-3000:]))
        return p.returncode == 0
    print("no LaTeX engine found (tectonic / latexmk / pdflatex); wrote report.tex only")
    return False


def fmt_rate(v, s):
    if v != v:
        return "--"
    if s == s and s > 0:
        return f"{v:.3g} $\\pm$ {s:.1g}"
    return f"{v:.4g}"


def checks_section(studies):
    """One table with every published number that a study can compare against."""
    lines = []
    for st in studies:
        mod = common.study_module(st)
        if not hasattr(mod, "checks"):
            continue
        try:
            rows = mod.checks(common.load_results(st))
        except Exception:  # noqa: BLE001
            traceback.print_exc()
            continue
        for r in rows:
            z = "--" if r["z"] != r["z"] else f"{r['z']:+.1f}"
            lines.append(f"{esc(st)} & {esc(r['label'])} & {r['variant']} & {r['quantity']} & {fmt_rate(r['paper'], r['paper_sigma'])} & "
                         f"{fmt_rate(r['ours'], r['ours_sigma'])} & {r['ratio']:.3f} & {z} \\\\")
    from repro import stim_check

    slines = []
    for st in studies:
        sr = stim_check.load(st)
        for name, r in sorted(common.load_results(st).items()):
            x = sr.get(name)
            if not x:
                continue
            for q in ("acceptance", "LER"):
                ref = dict(kept=x["kept"], shots=x["shots"]) if q == "acceptance" else dict(errors=x["errors"], kept=x["kept"])
                if q == "LER" and not x["errors"]:
                    continue
                c = common.check_row(name, "clifford", ref, r["totals"], quantity=q)
                if c:
                    z = "--" if c["z"] != c["z"] else f"{c['z']:+.1f}"
                    slines.append(f"{esc(st)} & {esc(name)} & {q} & {fmt_rate(c['paper'], c['paper_sigma'])} & "
                                  f"{fmt_rate(c['ours'], c['ours_sigma'])} & {common.fmt_count(x['shots'])} & {z} \\\\")
    stim_tab = ""
    if slines:
        stim_tab = ("\\subsection*{GPU kernel vs.\\ Stim on the same Clifford circuits}\n"
                    "Every Clifford-proxy point re-sampled with Stim on the CPU (\\texttt{repro/stim\\_check.py}), "
                    "same circuit file and postselection: an independent test of the Tsim GPU kernel.\n\n"
                    "{\\scriptsize\n\\begin{longtable}{l l l l l r r}\n\\toprule\nstudy & point & quantity & Stim (CPU) & Tsim GPU & Stim shots & $z$ \\\\\n"
                    "\\midrule\n\\endhead\n" + "\n".join(slines) + "\n\\bottomrule\n\\end{longtable}}\n")
    if not lines and not stim_tab:
        return ""
    return ("\\section*{Reproduction checks against published numbers}\\addcontentsline{toc}{section}{Reproduction checks}\n"
            "Every published number (tables, released data) that a sampled point can be compared with. $\\pm$: one standard "
            "deviation (Poisson for error counts, binomial for acceptance; published values without an uncertainty, or exact "
            "values, have none). $z$: difference over the combined standard deviation.\n\n"
            "{\\scriptsize\n\\begin{longtable}{l l l l l l r r}\n\\toprule\nstudy & point & variant & quantity & published & Tsim GPU & ratio & $z$ \\\\\n"
            "\\midrule\n\\endhead\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{longtable}}\n" + stim_tab + "\\clearpage\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*", default=None)
    ap.add_argument("--no-pdf", action="store_true")
    args = ap.parse_args()
    common.REPORT.mkdir(parents=True, exist_ok=True)
    studies = common.STUDY_ORDER if not args.only else [s for s in common.STUDY_ORDER if s in args.only]
    sections, rows, builds = [], [], set()
    for s in studies:
        try:
            sec, tot = study_section(s)
        except ModuleNotFoundError as e:
            print(f"{s}: skipped ({e})")
            continue
        sections.append(sec)
        for r in common.load_results(s).values():
            builds.add((r["tsim"].get("commit") or r["tsim"].get("version") or "?")[:10])
        rows.append(f"\\hyperref[sec:{s}]{{{esc(s)}}} & {tot['points']} & {common.fmt_seconds(tot['seconds'])} & "
                    f"{common.fmt_count(tot['shots'])} \\\\")
        print(f"{s}: {tot['points']} points, {common.fmt_seconds(tot['seconds'])}")
    checks = checks_section(studies)
    tex = common.REPORT / "report.tex"
    tex.write_text(preamble("\n".join(rows), ", ".join(sorted(builds)) or "none yet") + checks + "\n\n".join(sections)
                   + "\n\\end{document}\n")
    print(f"wrote {tex}")
    if not args.no_pdf:
        compile_pdf(tex)
    summary = {s: summarize(common.load_results(s)) for s in studies}
    (common.REPORT / "summary.json").write_text(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
